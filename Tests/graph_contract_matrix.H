/**
 * @file graph_contract_matrix.H
 * @brief What the files of the contract matrix of the graph templates,
 *        graph_contract_matrix_*_test.cc, share: the arc that the filters
 *        hide, and the loops over the filters of the catalog and over the
 *        constness of a graph.
 *
 * Each file kept a copy of them, so that a new filter of the catalog of
 * graph_filter_catalog.H had to be added to eight copies of
 * for_each_filter().
 */

#ifndef ALEPH_TESTS_GRAPH_CONTRACT_MATRIX_H
#define ALEPH_TESTS_GRAPH_CONTRACT_MATRIX_H

#include <cstddef>
#include <type_traits>
#include <utility>

#include <gtest/gtest.h>

#include <tpl_graph.H>

#include "graph_harness.H"
#include "graph_filter_catalog.H"

namespace graph_contract_matrix
{
  /// The number of the arc that the filters hide
  constexpr int Hidden = 2;

  /// The mask of the filters: only the arc Hidden
  const unsigned long Hidden_Mask = 1UL << Hidden;

  /// Whether a filter of type SA hides the arc Hidden: all but Dft_Show_Arc
  template <class GT, class SA>
  constexpr bool hides = not std::is_same_v<SA, Aleph::Dft_Show_Arc<GT>>;

  /** Calls f(sa, name) with a filter of each kind of the catalog of
      graph_filter_catalog.H, and with Dft_Show_Arc. All but Dft_Show_Arc
      hide the arc Hidden. f takes the filter by value, so that it can pass
      it on as an lvalue and as an rvalue. The filters whose call is not
      noexcept go through with_each_throw(), which calls f again throwing
      at each of their calls. */
  template <class GT, class F>
  void for_each_filter(F && f)
  {
    std::size_t calls = 0;
    f(Aleph::Dft_Show_Arc<GT>(), "Dft_Show_Arc");
    f(graph_filters::Hide_Mask<GT>{Hidden_Mask}, "Hide_Mask");
    f(graph_filters::Counting<GT>{Hidden_Mask, &calls}, "Counting");
    graph_harness::with_each_throw(f, graph_filters::make_capturing_lambda<GT>(Hidden_Mask), "Capturing_Lambda");
    f(graph_filters::Reference_Member<GT>(Hidden_Mask), "Reference_Member");
    f(graph_filters::Const_Member<GT>(Hidden_Mask), "Const_Member");
    graph_harness::with_each_throw(f, graph_filters::Throwing_Copy<GT>(Hidden_Mask), "Throwing_Copy");
    graph_harness::with_each_throw(f, graph_filters::Deque_Member<GT>(Hidden_Mask), "Deque_Member");
  }

  /// Calls f(g) with g as it is and as a const graph
  template <class GT, class F>
  void for_each_constness(GT & g, F && f)
  {
    {
      SCOPED_TRACE("GT &");
      f(g);
    }
    {
      SCOPED_TRACE("const GT &");
      f(std::as_const(g));
    }
  }
} // namespace graph_contract_matrix

#endif // ALEPH_TESTS_GRAPH_CONTRACT_MATRIX_H
